import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

test('production frontend: canonical routes, empty/outage states, mobile LINE link and archive gates', { skip: process.env.RUN_BROWSER_TESTS !== '1', timeout: 90000 }, async () => {
  const { preview } = await import('vite');
  const { chromium } = await import('playwright');
  const server = await preview({ root: fileURLToPath(new URL('../', import.meta.url)), preview: { host: '127.0.0.1', port: 0, strictPort: true } });
  let browser;
  try {
    const executablePath = ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(existsSync);
    browser = await chromium.launch({ ...(executablePath ? { executablePath } : {}), headless: true });
    const page = await browser.newPage({ viewport: { width: 320, height: 740 }, reducedMotion: 'reduce' });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const base = `http://127.0.0.1:${server.httpServer.address().port}`;
    let outage = false;
    let populated = false;
    const project = { id: 'fixture', slug: 'reviewed-fixture', title: { en: 'Reviewed fixture', th: 'ตัวอย่างที่อนุมัติ' }, summary: { en: 'Synthetic UI test only', th: 'ข้อมูลจำลองสำหรับทดสอบ UI เท่านั้น' }, status: 'prototype', category: 'automation' };
    await page.route('**/api/**', async route => {
      const pathname = new URL(route.request().url()).pathname;
      if (outage) return route.fulfill({ status: 503, json: { error: 'unavailable' } });
      if (pathname === '/api/chat') return route.fulfill({ json: { answer: 'Evidence for this synthetic UI test.', citations: [{ title: 'Fixture source', url: 'https://example.com/evidence' }] } });
      if (pathname === '/api/profile') return route.fulfill({ json: { profile: null, experiences: [], skills: [], projects: [] } });
      if (pathname === '/api/projects/reviewed-fixture') return route.fulfill({ json: { ...project, documents: [{ id: 'source', path: 'README.md', sha: 'a'.repeat(40), url: 'https://example.com/evidence', text: 'Reviewed synthetic evidence.' }] } });
      return route.fulfill({ json: populated ? [project] : [] });
    });
    await page.goto(`${base}/?lang=en`);
    await page.getByText('Awaiting approved content', { exact: true }).waitFor();
    assert.equal(await page.locator('html').getAttribute('lang'), 'en');
    assert.equal(await page.locator('a[href="/api/resume/ai-automation/en.pdf"]').count(), 1);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    const lineLink = page.locator('a.eva-launcher');
    await lineLink.waitFor();
    const box = await lineLink.boundingBox();
    assert.ok(box.x >= 0 && box.x + box.width <= 320);
    assert.equal(await lineLink.getAttribute('href'), 'https://line.me/R/ti/p/%40949xcfau');
    assert.equal(await lineLink.getAttribute('target'), '_blank');
    assert.match(await lineLink.getAttribute('rel'), /noopener/);
    await lineLink.focus();
    assert.equal(await lineLink.evaluate(element => document.activeElement === element), true);
    assert.deepEqual(await page.evaluate(() => Object.keys(sessionStorage)), []);
    assert.equal(await page.getByRole('dialog').count(), 0);
    assert.equal(await page.locator('button.eva-launcher').count(), 0);
    await page.goto(`${base}/resume/content-coordinator?lang=en`);
    await page.getByText('Awaiting approved content', { exact: true }).waitFor();
    assert.equal(await page.locator('select').inputValue(), 'content-coordinator');
    assert.equal(await page.locator('a[href="/api/resume/content-coordinator/en.pdf"]').count(), 1);
    assert.equal(await page.getByText(/4\+ years|Assistant Marketing Manager|186 Unit Tests/).count(), 0);
    await page.goto(`${base}/demo?lang=en`);
    await page.getByText('Legacy biography under review', { exact: true }).waitFor();
    assert.equal(await page.getByText(/186 Unit Tests|Solo Architecture/).count(), 0);
    populated = true;
    await page.goto(`${base}/projects?lang=en`);
    await page.getByRole('heading', { name: 'Reviewed fixture', exact: true }).waitFor();
    await page.getByRole('link', { name: 'Read case study', exact: true }).click();
    await page.getByRole('heading', { name: 'Reviewed fixture', exact: true }).waitFor();
    await page.getByText('README.md', { exact: true }).click();
    await page.getByText('Reviewed synthetic evidence.', { exact: true }).waitFor();
    assert.equal(await page.getByRole('link', { name: 'Open source' }).getAttribute('href'), 'https://example.com/evidence');
    outage = true;
    await page.goto(`${base}/projects?lang=en`);
    await page.getByText('Published content is unavailable', { exact: true }).waitFor();
    assert.ok(await page.getByRole('link', { name: 'Gallery', exact: true }).isVisible());
    await page.goto(`${base}/gallery?lang=en`);
    const photograph = page.getByRole('button', { name: 'Open photograph 1', exact: true });
    await photograph.waitFor();
    assert.equal(await page.locator('main img').count(), 39);
    await photograph.focus();
    await page.keyboard.press('Enter');
    await page.getByRole('dialog').waitFor();
    await page.keyboard.press('Escape');
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    assert.equal(await page.getByRole('dialog').count(), 0);
    assert.equal(await photograph.evaluate(element => document.activeElement === element), true);
    assert.deepEqual(errors, []);
  } finally { await browser?.close(); await new Promise(resolve => server.httpServer.close(resolve)); }
});
